#!/usr/bin/env python3
"""Generate worlds/sorting_cell.sdf from robotic_arm_control/config/task.yaml (re-run after editing the task).

usage: make_world.py <task.yaml> <out.sdf>
World frame: origin at the centre of the arm base on the table top, Z up.
"""
import math
import sys

import yaml

task = yaml.safe_load(open(sys.argv[1]))
st = task["stations"]
RGB = {"red": "0.85 0.10 0.10 1", "blue": "0.10 0.25 0.85 1"}


def xy(s):
    a = math.radians(s["azimuth_deg"])
    return s["r"] * math.cos(a), s["r"] * math.sin(a)


def box(name, size, pose, rgba, collide=True):
    col = f'<collision name="{name}_c"><pose>{pose}</pose><geometry><box><size>{size}</size></box></geometry></collision>' if collide else ""
    return (f'{col}<visual name="{name}_v"><pose>{pose}</pose><geometry><box><size>{size}</size></box></geometry>'
            f'<material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse><specular>0.1 0.1 0.1 1</specular></material></visual>')


def static_model(name, pose, body):
    return f'<model name="{name}"><static>true</static><pose>{pose}</pose><link name="link">{body}</link></model>\n'


out = ['''<?xml version="1.0"?>
<!-- generated by tools/make_world.py from task.yaml - Gazebo Fortress (SDF 1.8) -->
<sdf version="1.8">
<world name="sorting_cell">
  <physics name="1ms" type="ignored"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
  <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
  <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
  <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
  <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
  <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.93 0.94 0.96 1</background><shadows>true</shadows><grid>false</grid></scene>
  <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 3 0 0 0</pose>
    <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.4 0.3 -0.9</direction></light>
  <light type="point" name="fill"><pose>1.0 -1.0 1.2 0 0 0</pose><diffuse>0.5 0.5 0.5 1</diffuse><specular>0.1 0.1 0.1 1</specular>
    <attenuation><range>6</range><constant>0.6</constant><linear>0.1</linear><quadratic>0.02</quadratic></attenuation><cast_shadows>false</cast_shadows></light>
''']
out.append(static_model("floor", "0 0 -0.75 0 0 0",
                        '<collision name="c"><geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry></collision>'
                        '<visual name="v"><geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry>'
                        '<material><ambient>0.75 0.75 0.75 1</ambient><diffuse>0.75 0.75 0.75 1</diffuse></material></visual>'))
legs = "".join(box(f"leg{i}", "0.05 0.05 0.71", f"{x} {y} -0.395 0 0 0", "0.3 0.3 0.3 1")
               for i, (x, y) in enumerate([(0.5, 0.4), (0.5, -0.4), (-0.5, 0.4), (-0.5, -0.4)]))
out.append(static_model("table", "0.05 0 0 0 0 0", box("top", "1.2 1.0 0.04", "0 0 -0.02 0 0 0", "0.80 0.66 0.45 1") + legs))
px, py = xy(st["pick"])
s, h = st["pick"]["stand_size"], st["pick"]["surface_z"]
cube_yaw = math.radians(st["pick"]["azimuth_deg"] + task.get("tool", {}).get("jaw_yaw_deg", 0.0))   # cube faces parallel to the jaws
out.append(static_model("pick_stand", f"{px:.4f} {py:.4f} 0 0 0 {cube_yaw:.4f}",
                        box("stand", f"{s} {s} {h}", f"0 0 {h/2} 0 0 0", "0.35 0.35 0.38 1")))
for color in ("red", "blue"):
    b = st["bin_" + color]
    x, y = xy(b)
    o, w, fz, rz = b["outer"], b["wall"], b["floor_z"], b["rim_z"]
    light = RGB[color].replace(" 1", " 1")
    body = box("pedestal", f"{o} {o} {fz}", f"0 0 {fz/2} 0 0 0", "0.35 0.35 0.38 1")
    hw = rz - fz
    for i, (dx, dy, sx, sy) in enumerate([((o - w) / 2, 0, w, o), (-(o - w) / 2, 0, w, o), (0, (o - w) / 2, o, w), (0, -(o - w) / 2, o, w)]):
        body += box(f"wall{i}", f"{sx} {sy} {hw}", f"{dx} {dy} {fz + hw/2} 0 0 0", light)
    out.append(static_model("bin_" + color, f"{x:.4f} {y:.4f} 0 0 0 {math.radians(b['azimuth_deg']):.4f}", body))
c = task["payload"]["size"]
m = task["payload"]["mass"]
I = m * c * c / 6
fp = task["feeder_park"]
for i, cube in enumerate(task["cubes"]):
    if i == 0:
        pose = f"{px:.4f} {py:.4f} {h + c/2 + 0.001:.4f} 0 0 {cube_yaw:.4f}"
    else:
        pose = f"{fp['x']} {fp['y0'] + fp['dy'] * i:.3f} {c/2 + 0.001:.4f} 0 0 0"
    out.append(f'''<model name="{cube['name']}"><pose>{pose}</pose><link name="link">
  <inertial><mass>{m}</mass><inertia><ixx>{I:.3e}</ixx><iyy>{I:.3e}</iyy><izz>{I:.3e}</izz><ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia></inertial>
  <collision name="c"><geometry><box><size>{c} {c} {c}</size></box></geometry>
    <surface><friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction></surface></collision>
  <visual name="v"><geometry><box><size>{c} {c} {c}</size></box></geometry>
    <material><ambient>{RGB[cube['color']]}</ambient><diffuse>{RGB[cube['color']]}</diffuse><specular>0.2 0.2 0.2 1</specular></material></visual>
</link></model>
''')
# fixed camera for screenshots and the clip: looks at the cell from the front-right
cx, cy, cz = 0.75, -0.62, 0.52
tx, ty, tz = 0.08, 0.0, 0.20
yaw = math.atan2(ty - cy, tx - cx)
pitch = -math.atan2(tz - cz, math.hypot(tx - cx, ty - cy))
out.append(f'''<model name="cell_camera"><static>true</static><pose>{cx} {cy} {cz} 0 {pitch:.4f} {yaw:.4f}</pose><link name="link">
  <sensor name="camera" type="camera"><topic>cell_camera/image</topic><update_rate>30</update_rate><always_on>1</always_on>
    <camera><horizontal_fov>0.9</horizontal_fov><image><width>1280</width><height>720</height></image><clip><near>0.05</near><far>10</far></clip></camera>
  </sensor></link></model>
</world>
</sdf>
''')
open(sys.argv[2], "w").write("".join(out))
print("wrote", sys.argv[2])
