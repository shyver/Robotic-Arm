def f(x, n=2):
    return f"{x:.{n}f}"


def write_torque_table(res, out):
    with open(os.path.join(out, "torque_table.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["joint", "actuator", "available_Nm", "static_worst_pose_Nm", "required_x1.5_Nm", "margin",
                    "static_task_Nm", "required_task_x1.5_Nm", "margin_task"])
        for r in res["rows"]:
            w.writerow([r["joint"], r["actuator"], f(r["available"]), f(r["static"], 3), f(r["required"], 3), f(r["margin"]),
                        f(r["task_static"], 3), f(r["task_required"], 3), f(r["task_margin"])])
    with open(os.path.join(out, "torque_table.md"), "w") as fh:
        fh.write("| Joint | Actuator | Available (N·m) | Static (N·m) | Required × 1.5 (N·m) | Margin | Task static (N·m) | Task required × 1.5 (N·m) | Task margin |\n|---|---|---|---|---|---|---|---|---|\n")
        for r in res["rows"]:
            fh.write(f"| {r['joint']} | {r['actuator']} | {f(r['available'])} | {f(r['static'], 3)} | {f(r['required'], 3)} | {margin(r['margin'])} | "
                     f"{f(r['task_static'], 3)} | {f(r['task_required'], 3)} | {margin(r['task_margin'])} |\n")


def margin(m):
    return "> 100" if m > 100 else f(m)


