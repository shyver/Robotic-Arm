def find_runs(root):
    """newest Gazebo log with complete cycles, and newest log of the E-stop test."""
    cycles = estop = None
    if os.path.isdir(root):
        for d in sorted(os.listdir(root), reverse=True):
            p = os.path.join(root, d)
            if d == "latest" or not os.path.isdir(p):
                continue
            if estop is None and os.path.exists(os.path.join(p, "estop.csv")):
                estop = p
            c = os.path.join(p, "cycle.csv")
            if cycles is None and os.path.exists(c) and ",RETURN," in open(c).read():
                cycles = p
    return cycles, estop


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-dir", default=None)
    ap.add_argument("--estop-dir", default=None, help="log directory of the E-stop test (default: newest one found)")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--out", default="sim_evidence")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    img = os.path.join(out, "images", "sim")
    os.makedirs(img, exist_ok=True)
    run_dir, estop_dir = a.run_dir, a.estop_dir
    if run_dir is None and not a.offline:
        run_dir, found_estop = find_runs(os.path.expanduser("~/ras_arm_logs"))
        estop_dir = estop_dir or found_estop
    if run_dir is None:
        from . import offline_sim
        run_dir = os.path.join(out, "offline_run")
        os.makedirs(run_dir, exist_ok=True)
        print("== no Gazebo log given: running the offline simulation ==")
        offline_sim.run_cycles(run_dir)
        offline_sim.run_estop(run_dir)
        json.dump({"source": "offline"}, open(os.path.join(run_dir, "meta.json"), "w"))
    model, task, poses = load()
    run = read_run(run_dir)
    print(f"== figures from {run_dir} (source: {run['meta'].get('source')}) ==")
    R = dict(source=run["meta"].get("source", "unknown"), cycles=int(run["cycle"].max()), n_targets=len(poses.q) - 1,
             task=task, friction=model.joints["shoulder_lift_joint"]["friction"])
    cyc = run["cycle"] >= 1
    R["track_err_deg"] = float(np.abs(run["pos"] - run["des"])[cyc].max() / D) if "des" in run else float("nan")
    print("== static torque (URDF) ==")
    R["torque"] = static_torque.compute()
    print(static_torque.table_text(R["torque"]))
    write_torque_table(R["torque"], out)
    print("== time series ==")
    R["angles"] = plots.joint_angles(run, img)
    R["torques"] = plots.joint_torques(run, img, model)
    R["power"] = plots.power(run, img)
    R["homing"] = plots.homing(run, run_dir, img, task, poses)
    R["estop"] = plots.estop(estop_dir or run_dir, img)
    print("== workspace ==")
    ws = workspace.compute()
    workspace.figure(ws, img)
    R["workspace"] = {k: ws[k] for k in ("reach_max", "z_max", "tool_down_ok_r", "tool_down_ok_n", "tool_down_n")}
    print("== clearance ==")
    cl = clearance.compute(run_dir)
    clearance.figure(cl, img)
    R["clearance"] = dict(summary=cl["summary"], collision=cl["collision"])
    for k, v in cl["summary"].items():
        print(f"  min distance {k:9s}: {v['min_mm']:6.1f} mm at t = {v['t']:.1f} s ({v['state']}) {v['pair']}")
    R["poses_deg"] = {k: [round(float(x) / D, 2) for x in q] for k, q in poses.q.items()}
    R["start_pose_deg"] = [round(float(x) / D, 2) for x in poses.start]
    write_tex(R, out)
    json.dump(R, open(os.path.join(out, "results.json"), "w"), indent=1, default=float)
    print(f"== done: {out} ==")


if __name__ == "__main__":
    main()
