#!/usr/bin/env python3
"""Generate every figure, the torque table and simulation_section.tex with one command.

    ros2 run robotic_arm_analysis make_figures                    (after colcon build)
    python3 -m robotic_arm_analysis.make_figures                  (from src/robotic_arm_analysis, no ROS needed)

Options:
    --run-dir DIR   log directory written by the Gazebo demo (default: newest complete run in ~/ras_arm_logs;
                    if there is none, the offline simulation is run and used)
    --estop-dir DIR log directory of the Gazebo E-stop test (default: newest one in ~/ras_arm_logs)
    --offline       force the offline simulation
    --out DIR       output directory (default: ./sim_evidence)

Outputs in <out>/images/sim/: sim_joint_angles, sim_joint_torques, sim_workspace, sim_clearance, sim_power,
sim_homing, sim_estop (.pdf and .png, 200 dpi); in <out>/: simulation_section.tex, torque_table.csv/.md, results.json.
"""
