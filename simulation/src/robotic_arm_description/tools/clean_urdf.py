#!/usr/bin/env python3
"""Build the cleaned URDF/xacro from the raw SolidWorks sw_urdf_exporter output.

usage: clean_urdf.py <exported.urdf> <out_dir>      (writes robotic_arm.urdf.xacro and robotic_arm.urdf)

What it does (nothing else is touched: origins, axes, masses, COMs and inertias are copied verbatim):
  1. renames the robot/package, fixes package:// mesh paths, visual = original STL, collision = convex hull
  2. swaps the J4/J5 joint names and their child link names (export had them reversed)
  3. sets limits (range, effort, velocity) and dynamics (damping, friction) from the design table
  4. adds a `world` link and a fixed joint that stands the Y-up CAD model upright on the table (Z-up)
  5. checks every inertia tensor (positive definite + triangle inequality) and repairs invalid ones
  6. adds two prismatic gripper jaws, a `tcp` frame, ros2_control tags and the Gazebo (Fortress) plugins
"""
import math
import sys
import xml.etree.ElementTree as ET

import numpy as np

D = math.pi / 180.0
# ---------------------------------------------------------------- design data (see README, "Assumptions")
SWAP = {"wrist_roll_joint": "wrist_pitch_joint", "wrist_pitch_joint": "wrist_roll_joint",
        "wrist_roll_link": "wrist_pitch_link", "wrist_pitch_link": "wrist_roll_link"}
STEPPER = dict(effort=3.9, velocity=129.0 * D, damping=0.10, friction=0.30)
SERVO = dict(effort=1.96, velocity=400.0 * D, damping=0.05, friction=0.20)
# joint: (J-number, lower deg, upper deg, actuator)
JOINTS = {
    "base_rotation_joint": ("J1", -170, 170, STEPPER),
    "shoulder_lift_joint": ("J2", -100, 100, STEPPER),
    "elbow_joint":         ("J3", -135, 135, STEPPER),
    "wrist_pitch_joint":   ("J4", -135, 135, STEPPER),
    "wrist_roll_joint":    ("J5", -135, 135, SERVO),   # 270 deg version of the DS3218MG assumed
    "tool_rotation_joint": ("J6", -135, 135, SERVO),
}
BASE_BOTTOM_Y = 0.056      # lowest face of base_link in the CAD frame (CAD up = -Y), from the STL bounds
TOOL_TIP_Y = -0.284        # end of the tool_flange mesh along its local -Y (tool axis), from the STL bounds
JAW = dict(length=0.045, thick=0.006, width=0.020, mass=0.010, stroke=0.030, open_half=0.035,
           effort=40.0, velocity=0.10)
TCP_Y = TOOL_TIP_Y - 0.030  # grasp point: 30 mm beyond the mesh tip, between the jaws
COLORS = {"base_link": "0.20 0.20 0.22 1", "shoulder_link": "0.90 0.45 0.10 1", "upper_arm_link": "0.85 0.85 0.87 1",
          "forearm_link": "0.90 0.45 0.10 1", "wrist_pitch_link": "0.85 0.85 0.87 1",
          "wrist_roll_link": "0.90 0.45 0.10 1", "tool_flange_link": "0.25 0.25 0.28 1"}


def inertia_matrix(el):
    g = lambda k: float(el.get(k))
    return np.array([[g("ixx"), g("ixy"), g("ixz")], [g("ixy"), g("iyy"), g("iyz")], [g("ixz"), g("iyz"), g("izz")]])


def check_inertia(I):
    """returns (ok, principal moments). Valid: all > 0 and each <= sum of the two others."""
    w = np.linalg.eigvalsh(I)
    ok = w[0] > 0 and w[2] <= w[0] + w[1] + 1e-12
    return ok, w


def repair_inertia(I):
    """closest valid tensor: clip the principal moments, keep the principal axes."""
    w, V = np.linalg.eigh(I)
    w = np.maximum(w, 1e-7)
    if w[2] > w[0] + w[1]:
        w[2] = w[0] + w[1]
    return V @ np.diag(w) @ V.T


def pitch_axis_yaw(root):
    """yaw (about world Z) that puts the J2 axis exactly on world +Y at q = 0 (arm plane = world XZ at J1 = 0)."""
    def rpy(r, p, y):
        cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
        return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                         [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr], [-sp, cp * sr, cp * cr]])
    j = {e.get("name"): e for e in root.findall("joint")}
    R = rpy(-math.pi / 2, 0, 0)
    for n in ("base_rotation_joint", "shoulder_lift_joint"):
        R = R @ rpy(*map(float, j[n].find("origin").get("rpy").split()))
    a = R @ np.array(list(map(float, j["shoulder_lift_joint"].find("axis").get("xyz").split())))
    # +pi: with the tool pointing down (J5 = -41 deg) the tcp is then on the +X side for J1 near 0
    return -math.atan2(a[0], -a[1]) + math.pi, a


def build(src):
    root = ET.parse(src).getroot()
    report = []
    yaw, axis_before = pitch_axis_yaw(root)
    out = ET.Element("robot", {"name": "robotic_arm", "xmlns:xacro": "http://www.ros.org/wiki/xacro"})
    out.append(ET.Comment(" generated by tools/clean_urdf.py from the sw_urdf_exporter output; do not edit by hand "))
    ET.SubElement(out, "xacro:arg", {"name": "controllers_file", "default": "controllers.yaml"})
    ET.SubElement(out, "xacro:arg", {"name": "cubes", "default": "cube_1 cube_2 cube_3 cube_4"})

    # world + upright mounting (problem 2)
    ET.SubElement(out, "link", {"name": "world"})
    wj = ET.SubElement(out, "joint", {"name": "world_to_base", "type": "fixed"})
    ET.SubElement(wj, "origin", {"xyz": f"0 0 {BASE_BOTTOM_Y}", "rpy": f"{-math.pi/2:.6f} 0 {yaw:.6f}"})
    ET.SubElement(wj, "parent", {"link": "world"})
    ET.SubElement(wj, "child", {"link": "base_link"})
    report.append(f"world_to_base: xyz 0 0 {BASE_BOTTOM_Y}, rpy {-math.pi/2:.4f} 0 {yaw:.4f} "
                  f"(yaw {yaw/D:.2f} deg puts the J2 axis on world +Y at q=0)")

    for el in root:
        if el.tag == "link":
            old = el.get("name")
            new = SWAP.get(old, old)
            el.set("name", new)
            I_el = el.find("inertial/inertia")
            I = inertia_matrix(I_el)
            ok, w = check_inertia(I)
            status = "valid"
            if not ok:
                I2 = repair_inertia(I)
                for k, (a, b) in {"ixx": (0, 0), "ixy": (0, 1), "ixz": (0, 2), "iyy": (1, 1), "iyz": (1, 2), "izz": (2, 2)}.items():
                    I_el.set(k, f"{I2[a, b]:.6g}")
                status = "INVALID -> repaired, principal moments now " + np.array2string(check_inertia(I2)[1], precision=3)
            report.append(f"inertia {new:18s} m={float(el.find('inertial/mass').get('value')):.2f} kg  "
                          f"principal [{w[0]:.3e} {w[1]:.3e} {w[2]:.3e}]  {status}")
            vis, col = el.find("visual"), el.find("collision")
            vis.find("geometry/mesh").set("filename", f"package://robotic_arm_description/meshes/visual/{new}.STL")
            col.find("geometry/mesh").set("filename", f"package://robotic_arm_description/meshes/collision/{new}.stl")
            mat = vis.find("material")
            mat.set("name", new + "_color")
            mat.find("color").set("rgba", COLORS[new])
            out.append(el)
        elif el.tag == "joint":
            old = el.get("name")
            new = SWAP.get(old, old)
            el.set("name", new)
            el.set("type", "revolute")       # J1 was 'continuous': limited to +-170 deg (cables, homing switch)
            el.find("child").set("link", SWAP.get(el.find("child").get("link"), el.find("child").get("link")))
            el.find("parent").set("link", SWAP.get(el.find("parent").get("link"), el.find("parent").get("link")))
            jn, lo, hi, act = JOINTS[new]
            lim = el.find("limit")
            if lim is None:
                lim = ET.SubElement(el, "limit")
            lim.attrib.update(lower=f"{lo*D:.5f}", upper=f"{hi*D:.5f}", effort=f"{act['effort']}", velocity=f"{act['velocity']:.4f}")
            ET.SubElement(el, "dynamics", {"damping": str(act["damping"]), "friction": str(act["friction"])})
            out.append(el)
            report.append(f"joint {jn} {new:20s} (export name: {old:20s}) range [{lo}, {hi}] deg, effort {act['effort']} N.m, "
                          f"velocity {act['velocity']/D:.0f} deg/s, damping {act['damping']}, friction {act['friction']}")

    # gripper jaws + tcp (problem 9).  Jaws slide along tool_flange local X, tool axis is local -Y.
    def box_link(name, sx, sy, sz, m, rgba):
        l = ET.SubElement(out, "link", {"name": name})
        i = ET.SubElement(l, "inertial")
        ET.SubElement(i, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
        ET.SubElement(i, "mass", {"value": str(m)})
        ET.SubElement(i, "inertia", {"ixx": f"{m*(sy*sy+sz*sz)/12:.3e}", "ixy": "0", "ixz": "0",
                                      "iyy": f"{m*(sx*sx+sz*sz)/12:.3e}", "iyz": "0", "izz": f"{m*(sx*sx+sy*sy)/12:.3e}"})
        for tag in ("visual", "collision"):
            v = ET.SubElement(l, tag)
            ET.SubElement(v, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
            ET.SubElement(ET.SubElement(v, "geometry"), "box", {"size": f"{sx} {sy} {sz}"})
            if tag == "visual":
                ET.SubElement(ET.SubElement(v, "material", {"name": name + "_color"}), "color", {"rgba": rgba})
    J = JAW
    y_c = TOOL_TIP_Y - J["length"] / 2 + 0.005
    for side, sgn in (("left", 1.0), ("right", -1.0)):
        box_link(f"{side}_jaw_link", J["thick"], J["length"], J["width"], J["mass"], "0.1 0.1 0.1 1")
        j = ET.SubElement(out, "joint", {"name": f"{side}_jaw_joint", "type": "prismatic"})
        ET.SubElement(j, "origin", {"xyz": f"{sgn*(J['open_half']+J['thick']/2):.4f} {y_c:.4f} 0", "rpy": "0 0 0"})
        ET.SubElement(j, "parent", {"link": "tool_flange_link"})
        ET.SubElement(j, "child", {"link": f"{side}_jaw_link"})
        ET.SubElement(j, "axis", {"xyz": f"{-sgn:.0f} 0 0"})          # positive = closing, for both jaws
        ET.SubElement(j, "limit", {"lower": "0", "upper": str(J["stroke"]), "effort": str(J["effort"]), "velocity": str(J["velocity"])})
        ET.SubElement(j, "dynamics", {"damping": "2.0", "friction": "0.5"})
    ET.SubElement(out, "link", {"name": "tcp"})
    tj = ET.SubElement(out, "joint", {"name": "tcp_joint", "type": "fixed"})
    ET.SubElement(tj, "origin", {"xyz": f"0 {TCP_Y} 0", "rpy": "0 0 0"})
    ET.SubElement(tj, "parent", {"link": "tool_flange_link"})
    ET.SubElement(tj, "child", {"link": "tcp"})
    report.append(f"gripper: left/right_jaw_joint prismatic along tool_flange X, stroke {J['stroke']*1000:.0f} mm each, "
                  f"open gap {2*J['open_half']*1000:.0f} mm, 2 x {J['mass']*1000:.0f} g added; tcp at tool_flange y={TCP_Y}")

    # ros2_control (effort interface: needed so that the E-stop can remove the torque)
    rc = ET.SubElement(out, "ros2_control", {"name": "RoboticArmSim", "type": "system"})
    ET.SubElement(ET.SubElement(rc, "hardware"), "plugin").text = "ign_ros2_control/IgnitionSystem"
    names = list(JOINTS) + ["left_jaw_joint", "right_jaw_joint"]
    for n in names:
        eff = JOINTS[n][3]["effort"] if n in JOINTS else J["effort"]
        j = ET.SubElement(rc, "joint", {"name": n})
        c = ET.SubElement(j, "command_interface", {"name": "effort"})
        ET.SubElement(c, "param", {"name": "min"}).text = str(-eff)
        ET.SubElement(c, "param", {"name": "max"}).text = str(eff)
        p = ET.SubElement(j, "state_interface", {"name": "position"})
        ET.SubElement(p, "param", {"name": "initial_value"}).text = "${initial_%s}" % n if n in JOINTS else "0.0"
        ET.SubElement(j, "state_interface", {"name": "velocity"})
        ET.SubElement(j, "state_interface", {"name": "effort"})

    # Gazebo (Fortress) extensions
    g = ET.SubElement(out, "gazebo")
    pl = ET.SubElement(g, "plugin", {"filename": "ign_ros2_control-system", "name": "ign_ros2_control::IgnitionROS2ControlPlugin"})
    ET.SubElement(pl, "parameters").text = "$(arg controllers_file)"
    for i in range(1, 5):
        pl = ET.SubElement(g, "plugin", {"filename": "ignition-gazebo-detachable-joint-system",
                                         "name": "ignition::gazebo::systems::DetachableJoint"})
        for k, v in (("parent_link", "tool_flange_link"), ("child_model", f"cube_{i}"), ("child_link", "link"),
                     ("initial_attach", "false"), ("detach_topic", f"/grasp/cube_{i}/detach"),
                     ("attach_topic", f"/grasp/cube_{i}/attach"), ("output_topic", f"/grasp/cube_{i}/state"),
                     ("suppress_child_warning", "true")):
            ET.SubElement(pl, k).text = v
    for ln, rgba in COLORS.items():
        gr = ET.SubElement(out, "gazebo", {"reference": ln})
        ET.SubElement(gr, "self_collide").text = "false"
        m = ET.SubElement(ET.SubElement(gr, "visual"), "material")
        for k in ("ambient", "diffuse"):
            ET.SubElement(m, k).text = rgba
        ET.SubElement(m, "specular").text = "0.2 0.2 0.2 1"
    for side in ("left", "right"):
        gr = ET.SubElement(out, "gazebo", {"reference": f"{side}_jaw_link"})
        ET.SubElement(gr, "mu1").text = "1.0"
        ET.SubElement(gr, "mu2").text = "1.0"
    # keep the fixed-joint child frames (tcp) and do not lump world->base
    gr = ET.SubElement(out, "gazebo", {"reference": "tcp_joint"})
    ET.SubElement(gr, "preserveFixedJoint").text = "true"
    return out, report, axis_before


def main():
    src, out_dir = sys.argv[1], sys.argv[2]
    tree, report, _ = build(src)
    ET.indent(tree, space="  ")
    body = ET.tostring(tree, encoding="unicode")
    # initial (balanced) pose is injected as xacro properties so that it can be changed in one place
    props = "".join(f'  <xacro:arg name="initial_{n}" default="0.0"/>\n  <xacro:property name="initial_{n}" value="$(arg initial_{n})"/>\n' for n in JOINTS)
    body = body.replace('<link name="world"', props + '  <link name="world"', 1)
    xacro_txt = '<?xml version="1.0"?>\n' + body + "\n"
    open(f"{out_dir}/robotic_arm.urdf.xacro", "w").write(xacro_txt)
    # plain URDF (xacro resolved with defaults) for check_urdf and the offline analysis
    import re
    plain = re.sub(r"\s*<xacro:(arg|property)[^>]*/>\n?", "\n", xacro_txt)
    plain = re.sub(r"\$\{initial_[a-z_]+\}", "0.0", plain).replace("$(arg controllers_file)", "controllers.yaml")
    plain = plain.replace(' xmlns:xacro="http://www.ros.org/wiki/xacro"', "")
    open(f"{out_dir}/robotic_arm.urdf", "w").write(plain)
    print("\n".join(report))


if __name__ == "__main__":
    main()
